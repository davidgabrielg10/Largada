// Limite simples em memória (por instância). Basta para segurar spam e tentativas
// de adivinhar o PIN no porte deste projeto; não substitui um limitador distribuído.

const hits = new Map<string, number[]>();

/** true = pode seguir; false = excedeu `max` pedidos em `windowMs`. */
export function allow(key: string, max: number, windowMs: number, now = Date.now()): boolean {
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  if (recent.length >= max) {
    hits.set(key, recent);
    return false;
  }
  recent.push(now);
  hits.set(key, recent);
  if (hits.size > 5000) for (const [k, v] of hits) if (!v.some((t) => now - t < windowMs)) hits.delete(k);
  return true;
}

export function clientIp(headers: Headers): string {
  return headers.get("x-forwarded-for")?.split(",")[0]?.trim() || headers.get("x-real-ip") || "local";
}
